CREATE TABLE geographic_regions (
  id INTEGER NOT NULL,
  region_id VARCHAR(44),
  region_name VARCHAR(32),
  country_code VARCHAR(44),
  region_type VARCHAR(32),
  regulatory_authority VARCHAR(32),
  market_size DECIMAL,
  prevalence_rate DECIMAL,
  currency_code VARCHAR(44),
  language_code VARCHAR(32),
  time_zone VARCHAR(32),
  pharmaceutical_company_id INTEGER,
  hosts_rn_d_pharmaceutical_company_id INTEGER,
  drug_application_id INTEGER,
  disease_id VARCHAR(44),
  jurisdiction_for_regulation_drug_application_id INTEGER,
  PRIMARY KEY (id),
  FOREIGN KEY (pharmaceutical_company_id) REFERENCES pharmaceutical_companies (pharmaceutical_company_id),
  FOREIGN KEY (hosts_rn_d_pharmaceutical_company_id) REFERENCES pharmaceutical_companies (pharmaceutical_company_id),
  FOREIGN KEY (drug_application_id) REFERENCES drug_applications (drug_application_id),
  FOREIGN KEY (disease_id) REFERENCES diseases (disease_id),
  FOREIGN KEY (jurisdiction_for_regulation_drug_application_id) REFERENCES drug_applications (drug_application_id)
);
