CREATE TABLE drug_applications (
  drug_application_id INTEGER NOT NULL,
  application_id VARCHAR(32),
  application_type VARCHAR(32),
  drug_substance VARCHAR(32),
  approval_status VARCHAR(32),
  filing_date TIMESTAMP,
  approval_date TIMESTAMP,
  therapeutic_indication VARCHAR(32),
  dosage_form VARCHAR(32),
  strength VARCHAR(32),
  regulatory_authority VARCHAR(32),
  pharmaceutical_company_id INTEGER,
  transferred_from_pharmaceutical_company_id INTEGER,
  active_pharmaceutical_ingredient_api_id VARCHAR(44),
  geographic_region_id INTEGER,
  asset_transfer_id INTEGER,
  PRIMARY KEY (drug_application_id),
  FOREIGN KEY (pharmaceutical_company_id) REFERENCES pharmaceutical_companies (pharmaceutical_company_id),
  FOREIGN KEY (transferred_from_pharmaceutical_company_id) REFERENCES pharmaceutical_companies (pharmaceutical_company_id),
  FOREIGN KEY (active_pharmaceutical_ingredient_api_id) REFERENCES active_pharmaceutical_ingredients (api_id),
  FOREIGN KEY (geographic_region_id) REFERENCES geographic_regions (id),
  FOREIGN KEY (asset_transfer_id) REFERENCES asset_transfers (id)
);
