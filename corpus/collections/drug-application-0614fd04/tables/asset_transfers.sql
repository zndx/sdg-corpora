CREATE TABLE asset_transfers (
  id INTEGER NOT NULL,
  transfer_id VARCHAR(44),
  transfer_date TIMESTAMP,
  transfer_value DECIMAL,
  payment_structure VARCHAR(32),
  status VARCHAR(32),
  currency VARCHAR(32),
  effective_date TIMESTAMP,
  expiration_date TIMESTAMP,
  governing_law VARCHAR(32),
  confidentiality_level VARCHAR(32),
  drug_application_id INTEGER,
  pharmaceutical_company_id INTEGER,
  received_by_pharmaceutical_company_id INTEGER,
  geographic_region_id INTEGER,
  payment_id INTEGER,
  asset_transfer_id INTEGER,
  created_at TIMESTAMP,
  PRIMARY KEY (id),
  FOREIGN KEY (drug_application_id) REFERENCES drug_applications (drug_application_id),
  FOREIGN KEY (pharmaceutical_company_id) REFERENCES pharmaceutical_companies (pharmaceutical_company_id),
  FOREIGN KEY (received_by_pharmaceutical_company_id) REFERENCES pharmaceutical_companies (pharmaceutical_company_id),
  FOREIGN KEY (geographic_region_id) REFERENCES geographic_regions (id),
  FOREIGN KEY (payment_id) REFERENCES payments (payment_id),
  FOREIGN KEY (asset_transfer_id) REFERENCES asset_transfers (id)
);
