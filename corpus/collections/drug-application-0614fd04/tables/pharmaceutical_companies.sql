CREATE TABLE pharmaceutical_companies (
  pharmaceutical_company_id INTEGER NOT NULL,
  company_id VARCHAR(32),
  company_name VARCHAR(32),
  stock_ticker VARCHAR(32),
  stock_exchange VARCHAR(32),
  is_incorporated BOOLEAN,
  headquarters_location VARCHAR(32),
  primary_therapeutic_area VARCHAR(32),
  manufacturing_capacity INTEGER,
  api_supplier VARCHAR(61),
  finished_dosage_manufacturer VARCHAR(32),
  drug_application_id INTEGER,
  transfers_application_drug_application_id INTEGER,
  receives_application_drug_application_id INTEGER,
  active_pharmaceutical_ingredient_api_id VARCHAR(44),
  geographic_region_id INTEGER,
  has_subsidiary_pharmaceutical_company_id INTEGER,
  has_rn_d_location_geographic_region_id INTEGER,
  PRIMARY KEY (pharmaceutical_company_id),
  FOREIGN KEY (drug_application_id) REFERENCES drug_applications (drug_application_id),
  FOREIGN KEY (transfers_application_drug_application_id) REFERENCES drug_applications (drug_application_id),
  FOREIGN KEY (receives_application_drug_application_id) REFERENCES drug_applications (drug_application_id),
  FOREIGN KEY (active_pharmaceutical_ingredient_api_id) REFERENCES active_pharmaceutical_ingredients (api_id),
  FOREIGN KEY (geographic_region_id) REFERENCES geographic_regions (id),
  FOREIGN KEY (has_subsidiary_pharmaceutical_company_id) REFERENCES pharmaceutical_companies (pharmaceutical_company_id),
  FOREIGN KEY (has_rn_d_location_geographic_region_id) REFERENCES geographic_regions (id)
);
